// For loop
console.log("For loop:");
for (let i = 1; i <= 5; i++) {
    console.log("Count: " + i);
}

// While loop
console.log("\nWhile loop:");
let count = 1;
while (count <= 3) {
    console.log("Count: " + count);
    count++;
}

// Do-while loop
console.log("\nDo-while loop:");
let n = 1;
do {
    console.log("Number: " + n);
    n++;
} while (n <= 3);
